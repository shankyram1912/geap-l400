"""Summary and Agreement Metrics Analysis Engine.

This script reshapes the collected GEAP evaluation calls and responses,
and computes statistical summary and consistency metrics (Criteria Mean Score,
Standard Deviation, and Krippendorff's Alpha) across the evaluation passes.
"""

import argparse
import json
import os
import sys
from typing import Any, Dict, List, Set, Tuple

import pandas as pd
from tabulate import tabulate

from eval_harness.metrics_calc import compute_criterion_stats
from eval_harness.utils import load_eval_ratings_by_criterion, build_grades_dataframe, format_val


def get_formatted_criterion_metrics(
    grades_df: pd.DataFrame, criterion_id: str
) -> Dict[str, Any]:
    """Retrieves summary and agreement metrics for a single criterion.

    Args:
        grades_df: Pandas DataFrame containing scores from utils.build_grades_dataframe.
        criterion_id: Criterion ID.

    Returns:
        Dict[str, Any]: Dictionary containing computed metrics and basic info.
    """
    stats = compute_criterion_stats(grades_df)
    num_reports, num_eval_passes = stats["N"], stats["k"]

    return {
        "criterion_id": criterion_id,
        "mean": format_val(stats["mean"], "{:.4f}"),
        "min_rating": format_val(stats["min_rating"], "{:.0f}"),
        "max_rating": format_val(stats["max_rating"], "{:.0f}"),
        "max_range_report": "0" if num_eval_passes <= 1 else format_val(stats["max_range_report"], "{:.0f}", "0"),
        "max_range_pass": "0" if num_reports <= 1 else format_val(stats["max_range_pass"], "{:.0f}", "0"),
        "sd_report_means": format_val(stats["sd_report_means"], "{:.4f}"),
        "sd_pass_means": format_val(stats["sd_pass_means"], "{:.4f}"),
        "perc_agree": format_val(stats["mean_pa"], "{:.2%}"),
        "alpha": "N/A [Single Pass]" if num_eval_passes <= 1 else format_val(stats["alpha"], "{:.4f}"),
    }


def _is_numeric_cell(cell: str) -> bool:
    """Checks if a cell string represents a numeric value or common NA placeholders."""
    clean_cell = cell.replace("%", "").strip()
    if clean_cell in ["NA", "-", "N/A", ""]:
        return True
    try:
        float(clean_cell)
        return True
    except ValueError:
        return False


def robust_table_reformatter(raw_table_str: str) -> str:
    """Realigns columns in a markdown table to ensure consistent cell padding.

    Reads a raw markdown table string (typically generated by tabulate),
    calculates the maximum length of content in each column (ignoring markdown
    separator rows), and pads each cell so that columns align vertically.
    Maintains table structure and original row ordering.

    Args:
        raw_table_str: A string containing a markdown table with '|' delimiters.

    Returns:
        The formatted markdown table string with aligned columns.
    """
    lines = raw_table_str.strip().split("\n")
    if not lines:
        return ""

    rows_cells = []
    for line in lines:
        if line.startswith("|"):
            cells = [c.strip() for c in line.split("|")[1:-1]]
            rows_cells.append(cells)
        else:
            rows_cells.append(line)

    def is_separator(row):
        if isinstance(row, str):
            return True
        return all(all(char in "-:" for char in cell) for cell in row)

    grid_rows = [r for r in rows_cells if isinstance(r, list) and not is_separator(r)]
    if not grid_rows:
        return raw_table_str

    # Calculate column widths using zip to transpose rows
    col_widths = [max(len(cell) for cell in col) for col in zip(*grid_rows)]

    new_lines = []
    for row in rows_cells:
        if isinstance(row, str):
            new_lines.append(row)
            continue

        if is_separator(row):
            new_cells = ["-" * w for w in col_widths]
        else:
            new_cells = [
                cell.rjust(w) if _is_numeric_cell(cell) else cell.ljust(w)
                for cell, w in zip(row, col_widths)
            ]
        new_lines.append(f"| {' | '.join(new_cells)} |")

    return "\n".join(new_lines)


def get_metrics_definitions_str() -> str:
    """Returns the metric definitions as a formatted string."""
    return """
📈 Metric Definitions:
  • mean:             Criteria Mean Score (average rating across all reports and passes)
  • min/max rating:   Minimum / Maximum rating score assigned across all reports and passes
  • max range report: Widest rating range observed on a single report across passes
  • max range pass:   Widest rating range observed on a single pass across reports
  • sd report means:  Standard deviation of mean rating (across the k evaluation passes) for each report
  • sd pass means:    Standard deviation of mean rating (across all reports) for each eval pass
  • pairwise %_agree: Mean Pairwise Percent Agreement of Report Ratings
  • alpha:            Krippendorff's Alpha (global inter-rater agreement coefficient)"""


def format_summary_table(summary_df: pd.DataFrame, metrics_to_calc: List[str]) -> str:
    """Formats the summary DataFrame into a clean, aligned markdown table string.

    Reorders columns to place identifiers first, renames columns to display-friendly
    labels containing newlines, generates a markdown table via tabulate, and passes
    it through robust_table_reformatter to ensure proper alignment.

    Args:
        summary_df: A Pandas DataFrame containing computed metrics for all criteria.
        metrics_to_calc: List of metric names (keys in DataFrame) to include in the table.

    Returns:
        A formatted markdown table string representing the summary metrics.
    """
    # Reorder columns to make it clean
    columns_order = ["criterion_id", "criterion_name"]
    for m in metrics_to_calc:
        if m in summary_df.columns:
            columns_order.append(m)
    if "error" in summary_df.columns:
        columns_order.append("error")
    summary_df = summary_df[columns_order]

    # Rename columns for display representation
    rename_map = {
        "min_rating": "min\nrating",
        "max_rating": "max\nrating",
        "max_range_report": "max range\nreport",
        "max_range_pass": "max range\npass",
        "sd_report_means": "sd report\nmeans",
        "sd_pass_means": "sd pass\nmeans",
        "perc_agree": "pairwise\n%_agree"
    }
    summary_df = summary_df.rename(columns=rename_map)

    raw_table = tabulate(summary_df, headers="keys", tablefmt="github", showindex=False)
    formatted_table = robust_table_reformatter(raw_table)
    return formatted_table


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Calculate summary and agreement metrics (Mean, Sigma, Alpha) from GEAP call logs."
    )
    parser.add_argument(
        "--run_geap_eval_out",
        required=True,
        help="Path to eval calls and responses output by run_geap_eval.py",
    )

    args = parser.parse_args()

    metrics_to_calc = [
        "mean",
        "min_rating",
        "max_rating",
        "max_range_report",
        "max_range_pass",
        "sd_report_means",
        "sd_pass_means",
        "perc_agree",
        "alpha",
    ]

    try:
        # Load raw evaluation records and group flat ratings by criterion
        ratings_by_criterion = load_eval_ratings_by_criterion(args.run_geap_eval_out)

        # Compute metrics for each criterion
        summary_results = []
        for c_id in sorted(ratings_by_criterion.keys()):
            criterion_info = ratings_by_criterion[c_id]
            grades_df_by_crit = build_grades_dataframe(criterion_info["ratings"])
            res = get_formatted_criterion_metrics(grades_df_by_crit, c_id)
            res["criterion_name"] = criterion_info["name"]
            summary_results.append(res)

        summary_df = pd.DataFrame(summary_results)

        # Print beautiful terminal table
        print(get_metrics_definitions_str())
        print("\n=== GEAP Evaluation Metrics Summary ===")
        formatted_table = format_summary_table(summary_df, metrics_to_calc)
        print(formatted_table)

        # Print a bottom border matching the width of the table
        first_line = formatted_table.split("\n")[0] if formatted_table else ""
        table_width = len(first_line)
        if table_width > 0:
            print("=" * table_width)


    except Exception as e:
        print(f"❌ Error computing agreement metrics: {e}", file=sys.stderr)
        import traceback

        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
